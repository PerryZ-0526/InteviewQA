/**
 * 题目文本归一化（纯函数，供服务端与客户端共用）：
 * 英文标点转中文（逗号、分号、冒号、问号、叹号、圆括号；句点保留——序号 "1."、版本号、文件名中常见），
 * 并去除半角/全角空格（中文题面无需空格，英文术语紧贴中文）。
 */
export function normalizeQuestionText(text: string): string {
  return text
    // 英文标点 → 中文标点（冒号后跟 // 时不转，避免破坏 URL 的 "://"）
    .replace(/[,;!?()]/g, (c) =>
      ({ ',': '，', ';': '；', '!': '！', '?': '？', '(': '（', ')': '）' } as Record<string, string>)[c]
    )
    .replace(/:(?!\/)/g, '：')
    // 去掉所有空格（半角空格、制表符、全角空格）
    .replace(/[\t 　]+/g, '')
    .trim();
}
